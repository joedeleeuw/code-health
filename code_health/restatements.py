"""Restated Python instance shapes (code_health.shapes reads them).

Python decides class identity by name, so two classes that declare one shape
of at least three fields are separate types kept in step by hand. Two checks
share the matcher: one finding per shape that several first-party classes
declare, and one finding per first-party class whose shape a class exported by
a declared dependency already declares.

Shapes with different field names, or a field one requires and the other does
not, are different; a field whose requiredness is undecided on either side
leaves them undecided. Otherwise each field compares its two canonical types: the
same text naming no unresolved name is equal; a type that is unknown or names
an unresolved name, even the same unresolved name on both sides, is undecided;
two types that differ only where two external paths with one last name, or two
repository classes that may be one type, stand are undecided; any other
difference is different. Two repository classes with at least one field are
one type when their shapes are equal, and may be one type when their shapes
are undecided, decided from the types their fields name, repeatedly until
nothing more merges. Undecided shapes are never a restatement and never
dropped: the classes are reported as incomplete analysis at their declarations,
with what is unknown.

A field's owners are the repository classes at the root of the class's
ancestry that declare it; two classes restate one another only through at
least three fields with different owners, so subclasses refining a shared
ancestor's fields do not restate each other. A Protocol is a structural
interface that a class with its fields satisfies, so Protocols are matched only
with Protocols. Specimens, type-checker inputs and runner inputs
(code_health.specimens), classes of a module whose header declares that a tool
generated it, and vendored copies of third-party packages are not matched. A
class whose role the program leaves undecided is reported as incomplete
wherever it would restate another.
"""

import ast
import re
import tokenize
from dataclasses import dataclass
from itertools import combinations, islice
from pathlib import Path

from code_health.distribution import Distributions
from code_health.imports import Modules
from code_health.projects import Projects
from code_health.shapes import (
    MINIMUM_FIELDS,
    TOKEN,
    UNKNOWN_TYPE,
    ClassIndex,
    ShapedClass,
)
from code_health.specimens import Specimens

GENERATED = re.compile(
    r"@generated|\bauto-?generated\b|\bdo not edit\b|^\W*generated by\b"
    r"|\bthis (?:file|module) (?:is|was) (?:automatically )?generated\b",
    re.IGNORECASE | re.MULTILINE,
)
EQUAL, UNDECIDED, DIFFERENT = "equal", "undecided", "different"
MINIMUM_CLONE_LINES = 8


def canonical_ast(node: object) -> str:
    if isinstance(node, list):
        return f"[{','.join(canonical_ast(child) for child in node)}]"
    if not isinstance(node, ast.AST):
        return repr(node)
    if isinstance(node, ast.Constant):
        if isinstance(node.value, (str, bytes)):
            return "Constant('')"
        if isinstance(node.value, (int, float, complex)) and not isinstance(
            node.value, bool
        ):
            return "Constant(0)"
    parts = [
        f"{field}={canonical_ast(child)}" for field, child in ast.iter_fields(node)
    ]
    return f"{type(node).__name__}({','.join(parts)})"


def function_body_key(function: ast.FunctionDef | ast.AsyncFunctionDef) -> str | None:
    body = list(function.body)
    if (
        body
        and isinstance(body[0], ast.Expr)
        and isinstance(body[0].value, ast.Constant)
        and isinstance(body[0].value.value, str)
    ):
        body = body[1:]
    if len(body) < 2:
        return None
    end_line = body[-1].end_lineno or body[-1].lineno
    if end_line - body[0].lineno + 1 < MINIMUM_CLONE_LINES:
        return None
    return canonical_ast(body)


def unknown(text: str) -> bool:
    """The type is unknown or names an unresolved name."""
    return text == UNKNOWN_TYPE or "⟨U:" in text


def settled(key: tuple) -> bool:
    return not any(unknown(text) or required is None for _, text, required in key)


def outline(key: tuple) -> tuple:
    """The field names."""
    return tuple(name for name, *_ in key)


def loose(key: tuple) -> tuple:
    """A settled key with its repository classes and the modules of its
    external paths left out; only keys that share it can be undecided."""
    return tuple(
        (
            TOKEN.sub(
                lambda token: (
                    "⟨R⟩" if token[1] == "R" else f"⟨E:{token[2].rsplit('.', 1)[-1]}⟩"
                ),
                text,
            ),
            required,
        )
        for _, text, required in key
    )


def candidate_pairs(keys: list[tuple]):
    """The pairs of keys of one outline that may not be different."""
    by_loose: dict[tuple, list[tuple]] = {}
    unsettled = []
    for key in keys:
        if settled(key):
            by_loose.setdefault(loose(key), []).append(key)
        else:
            unsettled.append(key)
    for bucket in by_loose.values():
        yield from combinations(bucket, 2)
    for index, key in enumerate(unsettled):
        for other in [*unsettled[index + 1 :], *filter(settled, keys)]:
            yield key, other


class Partition:
    """Disjoint sets of members, each named by its member of least text."""

    def __init__(self):
        self.parent: dict = {}

    def find(self, member):
        while self.parent.get(member, member) != member:
            member = self.parent[member]
        return member

    def union(self, first, second) -> bool:
        self.parent.setdefault(first, first)
        self.parent.setdefault(second, second)
        first, second = self.find(first), self.find(second)
        if first == second:
            return False
        smaller, larger = sorted((first, second), key=str)
        self.parent[larger] = smaller
        return True


class Equivalence:
    """Which repository classes are one type and which may be one type, from
    the shapes they declare. External paths a second index resolves become that
    index's classes."""

    def __init__(self, typed: dict[str, tuple], translate=None):
        self.translate = translate or (lambda path: None)
        self.equal = Partition()
        self.possible = Partition()
        by_outline: dict[tuple, list[str]] = {}
        for identity, fields in typed.items():
            by_outline.setdefault(outline(fields), []).append(identity)
        buckets = [
            {identity: typed[identity] for identity in members}
            for members in by_outline.values()
            if len(members) > 1
        ]
        changed = True
        while changed:
            changed = False
            for bucket in buckets:
                changed |= self.merge(bucket)

    def merge(self, bucket: dict[str, tuple]) -> bool:
        """Merge the classes of one outline whose shapes are equal, and mark
        those whose shapes are undecided as possibly one type."""
        keyed: dict[tuple, list[str]] = {}
        for identity, fields in bucket.items():
            keyed.setdefault(self.key(fields), []).append(identity)
        changed = False
        for key, identities in keyed.items():
            for other in identities[1:]:
                if settled(key):
                    changed |= self.equal.union(identities[0], other)
                changed |= self.possible.union(identities[0], other)
        for first, second in candidate_pairs(list(keyed)):
            if self.compare(first, second) != DIFFERENT:
                changed |= self.possible.union(keyed[first][0], keyed[second][0])
        return changed

    def token(self, match: re.Match) -> str:
        kind, path = match[1], match[2]
        if kind == "E" and (resolved := self.translate(path)):
            kind, path = "R", resolved
        if kind == "R":
            return f"⟨R:{self.equal.find(path)}⟩"
        return match[0]

    def key(self, fields: tuple) -> tuple:
        return tuple(
            (name, TOKEN.sub(self.token, text), required)
            for name, text, required in fields
        )

    def compare(self, first: tuple, second: tuple) -> str:
        """Whether two keys of one outline are equal, undecided or different;
        Any, declared or standing for a generic's missing arguments, is one
        declared type like any other and equals only itself."""
        verdict = EQUAL
        for (_, left, needed), (_, right, other) in zip(first, second, strict=True):
            if needed != other and None not in (needed, other):
                return DIFFERENT
            if None in (needed, other) or unknown(left) or unknown(right):
                verdict = UNDECIDED
            elif left != right:
                if not self.comparable(left, right):
                    return DIFFERENT
                verdict = UNDECIDED
        return verdict

    def comparable(self, left: str, right: str) -> bool:
        """Two settled types that agree everywhere but at names that are two
        external paths with one last name or two classes that may be one
        type."""
        left_parts, right_parts = TOKEN.split(left), TOKEN.split(right)
        if len(left_parts) != len(right_parts):
            return False
        for index in range(0, len(left_parts), 3):
            if left_parts[index] != right_parts[index]:
                return False
            if index + 2 >= len(left_parts):
                continue
            kind, other_kind = left_parts[index + 1], right_parts[index + 1]
            path, other_path = left_parts[index + 2], right_parts[index + 2]
            if kind != other_kind:
                return False
            if path == other_path:
                continue
            if kind == "E" and path.rsplit(".", 1)[-1] == other_path.rsplit(".", 1)[-1]:
                continue
            if kind == "R" and self.possible.find(path) == self.possible.find(
                other_path
            ):
                continue
            return False
        return True


def described(fields: tuple) -> str:
    return ", ".join(name for name, *_ in fields)


def unknown_fields(shaped: ShapedClass) -> list[str]:
    """What leaves each unknown field type of the class unknown."""
    found = []
    for name, text, required in shaped.fields:
        if required is None:
            found.append(
                f"{shaped.qualname}.{name} may be required or optional: what "
                "provides its constructor, or how, does not resolve"
            )
        if text == UNKNOWN_TYPE:
            found.append(f"{shaped.qualname}.{name} is stored without a declared type")
        found += [
            f"{shaped.qualname}.{name} names {token[2]}, which does not resolve"
            for token in TOKEN.finditer(text)
            if token[1] == "U"
        ]
    return found


@dataclass
class Restatements:
    """Restatement findings by each file that holds a member, and incomplete
    analysis by the file it stands in."""

    findings: dict[str, list[str]]
    incomplete: dict[str, list[str]]


def linked_keys(groups: dict, equivalence: Equivalence) -> list[list[tuple]]:
    """The sets of shape keys of one outline joined by undecided comparisons,
    and each unsettled key two classes share."""
    by_outline: dict[tuple, list[tuple]] = {}
    for key in groups:
        by_outline.setdefault(outline(key), []).append(key)
    linked = Partition()
    for keys in by_outline.values():
        for key in keys:
            if not settled(key) and len(groups[key]) > 1:
                linked.union(key, key)
        for first, second in candidate_pairs(keys):
            if equivalence.compare(first, second) == UNDECIDED:
                linked.union(first, second)
    components: dict[tuple, list[tuple]] = {}
    for key in linked.parent:
        components.setdefault(linked.find(key), []).append(key)
    return list(components.values())


class FirstPartyShapes:
    """The repository's classes by shape, and which of them hold their shape:
    not specimens, runner inputs or type-checker inputs, not vendored copies,
    and not in a module whose header, the comments before its first statement
    and its docstring, declares that a tool generated it from an input that
    owns the shape."""

    def __init__(
        self,
        root: Path,
        modules: Modules,
        projects: Projects,
        shipped: Distributions,
    ):
        self.root = root
        self.trees = modules.trees
        self.index = ClassIndex(modules)
        self.specimens = Specimens(modules, projects, shipped)
        self.projects = projects
        self.generated: dict[str, bool] = {}
        self.standings: dict[str, bool | str] = {}

    def generated_module(self, path: str) -> bool:
        if path not in self.generated:
            tree = self.trees[path]
            end = tree.body[0].lineno - 1 if tree.body else None
            with tokenize.open(self.root / path) as source:
                header = "".join(islice(source, end))
            docstring = ast.get_docstring(tree) or ""
            self.generated[path] = bool(GENERATED.search(header + docstring))
        return self.generated[path]

    def program_module(self, path: str) -> bool | str:
        """Whether the module holds the program's own classes: not generated,
        not a vendored copy and not a type-checker input; what leaves that
        undecided otherwise."""
        if self.generated_module(path) or self.projects.vendored(path):
            return False
        checker = self.specimens.type_checker_input(path)
        return checker if isinstance(checker, str) else not checker

    def standing(self, shaped: ShapedClass) -> bool | str:
        """Whether the class holds its shape, or what leaves that undecided; a
        class the test runner collects is the runner's input, not a shape."""
        if shaped.identity not in self.standings:
            self.standings[shaped.identity] = self.role(shaped)
        return self.standings[shaped.identity]

    def role(self, shaped: ShapedClass) -> bool | str:
        program = self.program_module(shaped.path)
        if program is False:
            return False
        if self.test_case(shaped):
            return False
        names = {name for name, *_ in shaped.fields}
        specimen = self.specimens.specimen(shaped.path, shaped.node, names)
        local = self.specimens.local_evidence(shaped.path, shaped.node)
        runner = local.runner_input() if local else False
        if runner is True:
            return False
        if specimen is True:
            escape = local.collected_escape() if local else False
            if escape is False:
                return False
            specimen = escape if isinstance(escape, str) else False
        roles = [
            f"{shaped} is a {role}, which {why} decides"
            for role, why in (
                ("type-checker input", program),
                ("specimen", specimen),
                ("runner input", runner),
            )
            if isinstance(why, str)
        ]
        return "; ".join(roles) or True

    def test_case(self, shaped: ShapedClass) -> bool:
        """Whether the class is test code: the test runner collects a method
        of it or of a repository ancestor, by its own collection rules (file,
        class and function patterns, unittest bases, hooks), or the class is
        declared at module level in a collected file inside a test tree the
        runner collects by default, where every class is the tests' own
        helper."""
        runner = self.specimens.runner
        parent = self.specimens.module(shaped.path).parent_of[id(shaped.node)]
        if (
            isinstance(parent, ast.Module)
            and runner.collects_case(shaped.path)
            and runner.collects_tree(shaped.path)
        ):
            return True
        return any(
            runner.collected(declared.path, member) is True
            for ancestor in (shaped.identity, *self.index.ancestry(shaped.identity))
            for declared in (self.index.classes[ancestor],)
            for member in declared.node.body
            if isinstance(member, (ast.FunctionDef, ast.AsyncFunctionDef))
        )

    def restating_kinds(self, members: list[ShapedClass]) -> list[ShapedClass]:
        """The restating members, concrete classes and Protocols apart."""
        return [
            shaped
            for protocol in (False, True)
            for shaped in self.restating(
                [member for member in members if member.protocol == protocol]
            )
        ]

    def restating(self, members: list[ShapedClass]) -> list[ShapedClass]:
        """The members that restate another: at least the minimum number of
        fields whose owners differ between the two."""
        kept = []
        for first, second in combinations(members, 2):
            different = sum(
                self.index.owners(first.identity, name)
                != self.index.owners(second.identity, name)
                for name, *_ in first.fields
            )
            if different >= MINIMUM_FIELDS:
                kept += [member for member in (first, second) if member not in kept]
        return [member for member in members if member in kept]

    def unreadable(self) -> list[tuple[str, str]]:
        """The program's classes whose shape is unknown, by file."""
        return [
            (entry.split("::", 1)[0], entry)
            for entry in self.index.unreadable
            if self.program_module(entry.split("::", 1)[0]) is not False
        ]

    def undecided(self, groups: dict, components: list[list[tuple]]):
        """Each set of classes, from the components of linked shape keys, that
        may restate one another but whose shapes compare undecided, with what
        leaves the comparison and their roles undecided."""
        for keys in components:
            standing = {
                shaped.identity: self.standing(shaped)
                for key in keys
                for shaped in groups[key]
            }
            members = self.restating_kinds(
                [
                    shaped
                    for key in keys
                    for shaped in groups[key]
                    if standing[shaped.identity] is not False
                ]
            )
            involved = [key for key in keys if any(m in groups[key] for m in members)]
            if len({member.identity for member in members}) < 2 or (
                len(involved) == 1 and settled(involved[0])
            ):
                continue
            reasons = [
                reason for member in members for reason in unknown_fields(member)
            ]
            if len(involved) > 1:
                reasons.append(
                    "their other field types differ only where external paths with "
                    "one last name, or classes that may be one type, stand"
                )
            reasons += [
                standing[member.identity]
                for member in members
                if isinstance(standing[member.identity], str)
            ]
            yield members, list(dict.fromkeys(reasons))

    def clone_groups(self) -> Restatements:
        """One finding per shape that two first-party classes of one kind
        declare; incomplete analysis for each set of classes whose comparison or
        role is undecided and each class whose shape is unknown."""
        equivalence = Equivalence(self.index.typed)
        groups: dict[tuple, list[ShapedClass]] = {}
        for shaped in self.index.shapes:
            groups.setdefault(equivalence.key(shaped.fields), []).append(shaped)
        findings: dict[str, list[str]] = {}
        incomplete = self.unreadable()
        for key, classes in groups.items():
            if len(classes) < 2 or not settled(key):
                continue
            standing = {shaped.identity: self.standing(shaped) for shaped in classes}
            fields = described(classes[0].fields)
            restating = self.restating_kinds(
                [shaped for shaped in classes if standing[shaped.identity] is True]
            )
            if restating:
                for path in sorted({shaped.path for shaped in restating}):
                    findings.setdefault(path, []).append(
                        f"{' = '.join(map(str, restating))} ({fields})"
                    )
            possible = self.restating_kinds(
                [shaped for shaped in classes if standing[shaped.identity] is not False]
            )
            roles = [
                standing[shaped.identity]
                for shaped in possible
                if isinstance(standing[shaped.identity], str)
            ]
            if roles:
                incomplete.append(
                    (
                        possible[0].path,
                        f"{' = '.join(map(str, possible))} ({fields}) restate one "
                        f"another unless {'; '.join(roles)}",
                    )
                )
        components = linked_keys(groups, equivalence)
        for members, reasons in self.undecided(groups, components):
            incomplete.append(
                (
                    members[0].path,
                    f"{' ~ '.join(map(str, members))} ({described(members[0].fields)}) "
                    f"may restate one another: {'; '.join(reasons)}",
                )
            )
        by_file: dict[str, list[str]] = {}
        for path, note in sorted(incomplete):
            by_file.setdefault(path, []).append(note)
        for members in self.function_clones():
            for path in sorted({path for path, _ in members}):
                sites = " = ".join(site for _, site in members)
                findings.setdefault(path, []).append(sites)
        return Restatements(findings, by_file)

    def production_functions(
        self, path: str, tree: ast.Module
    ) -> list[tuple[str, str]]:
        if self.program_module(path) is not True:
            return []
        runner = self.specimens.runner
        if runner.collects_case(path) and runner.collects_tree(path):
            return []
        module = self.specimens.module(path)
        found: list[tuple[str, str]] = []
        scopes = [tree, *(n for n in ast.walk(tree) if isinstance(n, ast.ClassDef))]
        for scope in scopes:
            in_class = isinstance(scope, ast.ClassDef)
            if in_class and scope.bases:
                continue
            for member in scope.body:
                if not isinstance(member, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    continue
                if runner.collected(path, member) is not False:
                    continue
                if self.specimens.fixture_function(module, member):
                    continue
                if (key := function_body_key(member)) is not None:
                    qualname = (
                        f"{scope.name}.{member.name}" if in_class else member.name
                    )
                    found.append((key, f"{path}::{qualname}:{member.lineno}"))
        return found

    def function_clones(self) -> list[list[tuple[str, str]]]:
        by_body: dict[str, list[tuple[str, str]]] = {}
        for path, tree in sorted(self.trees.items()):
            for key, site in self.production_functions(path, tree):
                by_body.setdefault(key, []).append((path, site))
        return sorted(members for members in by_body.values() if len(members) >= 2)

    def dependency_clones(self, shapes: "ExportedShapes") -> list[str]:
        """One finding per first-party class whose shape an exported dependency
        class of the same kind declares, unless that class is the class's own
        base or the class itself: a dependency built from the repository's own
        sources exports the first-party classes. A class whose comparison with
        an exported class, or whose role, is undecided is incomplete."""
        findings = [f"incomplete: {entry}" for _, entry in self.unreadable()]
        for shaped in self.index.shapes:
            names = {name for name, *_ in shaped.fields}
            if len(names - shaped.inherited) < MINIMUM_FIELDS:
                continue
            restated, unsettled = shapes.matches(shaped)
            if restated or unsettled:
                findings += self.dependency_findings(
                    shaped, restated, [shapes.classes[name] for name in unsettled]
                )
        return findings

    def dependency_findings(
        self, shaped: ShapedClass, restated: list[str], unsettled: list[ShapedClass]
    ) -> list[str]:
        """The finding for a class that restates exported classes, and the
        incomplete analysis for its undecided comparisons and role."""
        standing = self.standing(shaped)
        fields = described(shaped.fields)
        found = []
        if restated and standing is True:
            found.append(f"{shaped} restates {', '.join(restated)} ({fields})")
        elif restated and isinstance(standing, str):
            found.append(
                f"incomplete: {shaped} restates {', '.join(restated)} ({fields}) "
                f"unless {standing}"
            )
        if unsettled and standing is not False:
            reasons = [
                reason
                for other in [shaped, *unsettled]
                for reason in unknown_fields(other)
            ] or [
                "its field types differ from theirs only where external paths "
                "with one last name, or classes that may be one type, stand"
            ]
            if isinstance(standing, str):
                reasons.append(standing)
            names = ", ".join(other.identity for other in unsettled)
            found.append(
                f"incomplete: {shaped} ({fields}) may restate {names}: "
                f"{'; '.join(reasons)}"
            )
        return found


class ExportedShapes:
    """The shapes a dependency's exported classes declare, compared with the
    first-party classes through one equivalence. External paths in
    first-party types are resolved through the dependency's modules."""

    def __init__(self, dependency: ClassIndex, exported: set[str], typed: dict):
        def translate(path: str) -> str | None:
            match = TOKEN.fullmatch(dependency.resolve(path))
            return match[2] if match and match[1] == "R" else None

        self.equivalence = Equivalence(dependency.typed | typed, translate)
        self.owners: dict[tuple, set[str]] = {}
        for shaped in dependency.shapes:
            if shaped.identity in exported:
                key = self.equivalence.key(shaped.fields)
                self.owners.setdefault((key, shaped.protocol), set()).add(
                    shaped.identity
                )
        self.by_outline: dict[tuple, list[tuple]] = {}
        for key, protocol in self.owners:
            self.by_outline.setdefault((outline(key), protocol), []).append(key)
        self.classes = {shaped.identity: shaped for shaped in dependency.shapes}

    def matches(self, shaped: ShapedClass) -> tuple[list[str], list[str]]:
        """The exported classes the class restates, and those whose comparison
        with it is undecided, its own bases and itself aside."""
        key = self.equivalence.key(shaped.fields)
        own = {shaped.identity, *shaped.bases}
        restated = set()
        if settled(key):
            restated = self.owners.get((key, shaped.protocol), set()) - own
        unsettled = {
            identity
            for other in self.by_outline.get((outline(key), shaped.protocol), [])
            if self.undecided(key, other)
            for identity in self.owners[other, shaped.protocol]
        }
        return sorted(restated), sorted(unsettled - own)

    def undecided(self, key: tuple, other: tuple) -> bool:
        if key == other:
            return not settled(key)
        return self.equivalence.compare(key, other) == UNDECIDED
